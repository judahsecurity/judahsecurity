import hashlib
import json
import logging
import os
import time
import uuid
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional
from urllib.parse import urlsplit

logger = logging.getLogger(__name__)

PRIOR_MEMORY_NOTE = (
    "Prior-run context for this origin. Not evidence: re-test before relying on it, "
    "and never cite it as proof."
)

_MAX_PATTERNS = 50
_MAX_SIGNATURES = 30
_MAX_BYPASS = 30
_MAX_EXHAUSTED_KEYS = 200
_MAX_TECHNIQUES_PER_KEY = 25
_MAX_PAYLOAD_CATEGORIES = 40
_MAX_PAYLOADS_PER_CATEGORY = 20
_MAX_TEXT = 200
_MAX_FILE_BYTES = 512_000
_BODY_SCAN_CHARS = 4096

# Vendor name -> lowercase substrings that identify it in header names,
# header values ("server", "via", "x-cdn") or a block page body.
_WAF_VENDORS = (
    ("cloudflare", ("cf-ray", "cloudflare", "__cfduid", "cf-mitigated", "cloudflare ray id")),
    ("akamai", ("akamaighost", "akamai", "x-akamai", "akamai-grn")),
    ("imperva", ("incapsula", "imperva", "x-iinfo", "incap_ses", "visid_incap")),
    ("sucuri", ("x-sucuri", "sucuri")),
    ("f5 big-ip", ("big-ip", "bigip", "x-wa-info", "f5 big-ip", "bigipserver")),
    ("aws waf", ("aws waf", "awselb", "x-amzn-waf", "awswaf")),
    ("modsecurity", ("mod_security", "modsecurity", "this error was generated by mod_security")),
    ("fortiweb", ("fortiweb", "fortiwafsid")),
    ("barracuda", ("barracuda", "barra_counter_session")),
    ("wordfence", ("wordfence",)),
    ("reblaze", ("reblaze", "rbzid")),
    ("wallarm", ("wallarm", "nginx-wallarm")),
    ("azure front door", ("x-azure-ref", "azure front door")),
    ("fastly", ("x-fastly-request-id", "fastly")),
)
# Body markers -> fixed signature labels. The label, never page text, is stored.
_BLOCK_MARKERS = (
    ("blocked by waf", "waf_block_page"),
    ("waf block", "waf_block_page"),
    ("request blocked", "request_blocked"),
    ("the requested url was rejected", "request_rejected"),
    ("attention required", "challenge_page"),
    ("cloudflare ray id", "challenge_page"),
    ("checking your browser", "challenge_page"),
    ("captcha", "captcha"),
    ("security check", "challenge_page"),
    ("access denied", "access_denied"),
    ("not acceptable", "not_acceptable"),
    ("rate limit", "rate_limited"),
    ("rate-limit", "rate_limited"),
    ("too many requests", "rate_limited"),
    ("429 too many", "rate_limited"),
)
_BLOCK_STATUSES = (403, 406, 429, 501, 503)


def _now() -> float:
    return time.time()


def _clean(value: Any, limit: int = _MAX_TEXT) -> str:
    """Bound and redact one stored string; drop target-authored instructions."""
    from app.services.agent.observability import redact_string
    from app.services.agent.palace_memory import (
        contains_indirect_prompt_injection,
        redact_for_palace,
    )

    text = " ".join(str(value or "").split())
    if not text:
        return ""
    text = redact_for_palace(redact_string(text))
    if contains_indirect_prompt_injection(text):
        return ""
    return text[:limit]


def _union_front(existing: Iterable[str], new: Iterable[str], limit: int) -> List[str]:
    """Newest first, de-duplicated, bounded."""
    out: List[str] = []
    for item in [*new, *existing]:
        if item and item not in out:
            out.append(item)
    return out[:limit]


def _brain_dict(manager_or_brain: Any) -> Optional[Dict[str, Any]]:
    """Return the session brain dict (mutable in place) for a manager or brain."""
    if isinstance(manager_or_brain, dict):
        return manager_or_brain
    if hasattr(manager_or_brain, "defense_profile"):
        return None
    brain = getattr(manager_or_brain, "_engagement_brain", None)
    if not isinstance(brain, dict):
        brain = {}
        try:
            manager_or_brain._engagement_brain = brain
        except Exception:
            return None
    return brain


def _profile_of(brain: Any) -> Dict[str, Any]:
    if isinstance(brain, dict):
        profile = brain.get("defense_profile")
        if not isinstance(profile, dict):
            profile = brain["defense_profile"] = {}
        return profile
    profile = getattr(brain, "defense_profile", None)
    if not isinstance(profile, dict):
        profile = {}
        brain.defense_profile = profile
    return profile


def _field(brain: Any, name: str) -> Dict[str, List[str]]:
    if isinstance(brain, dict):
        value = brain.get(name)
        if not isinstance(value, dict):
            value = brain[name] = {}
        return value
    value = getattr(brain, name, None)
    if not isinstance(value, dict):
        value = {}
        setattr(brain, name, value)
    return value


# ---------------------------------------------------------------- detection


def detect_vendor(headers: Optional[Dict[str, Any]] = None, body: str = "") -> str:
    """Name the WAF/edge vendor from response headers or a block page body."""
    hay_parts = []
    for key, value in (headers or {}).items():
        lowered_key = str(key).lower()
        if lowered_key in ("set-cookie", "cookie"):
            # Cookie names identify vendors; never keep their values.
            value = ";".join(part.split("=", 1)[0] for part in str(value).split(";"))
        hay_parts.append(f"{lowered_key}: {str(value).lower()}")
    hay_parts.append(str(body or "")[:_BODY_SCAN_CHARS].lower())
    hay = "\n".join(hay_parts)
    for vendor, markers in _WAF_VENDORS:
        if any(marker in hay for marker in markers):
            return vendor
    return ""


def classify_response(
    status: Any,
    headers: Optional[Dict[str, Any]] = None,
    body: str = "",
) -> Dict[str, Any]:
    """Classify one response cheaply. Returns fixed labels only, never page text.

    ``blocked`` is set only when a block status comes with a vendor or a known
    block-page marker, or for 429, so an application 403 (authorization) is not
    mistaken for a WAF.
    """
    try:
        code = int(status)
    except (TypeError, ValueError):
        code = 0
    low = str(body or "")[:_BODY_SCAN_CHARS].lower()
    vendor = detect_vendor(headers, body)
    marker = next((label for token, label in _BLOCK_MARKERS if token in low), "")
    blocked = code == 429 or (code in _BLOCK_STATUSES and bool(vendor or marker))
    if code == 429 and not marker:
        marker = "rate_limited"
    return {"status": code, "vendor": vendor, "marker": marker if blocked else "", "blocked": blocked}


def read_defense(raw: Any) -> Optional[Dict[str, Any]]:
    """Vanguard-compatible reader: ``None`` unless the response looks defended.

    Accepts the raw tool output (JSON text with ``status``/``body``) or a dict.
    Looser than ``classify_response``: any 403/429/503 or block token counts,
    as in Vanguard. Automatic brain updates use ``classify_response``.
    """
    if not raw:
        return None
    obj: Any = raw
    if isinstance(raw, str):
        try:
            obj = json.loads(raw)
        except (TypeError, ValueError):
            obj = None
    status = None
    headers: Dict[str, Any] = {}
    if isinstance(obj, dict):
        s = obj.get("status") or obj.get("status_code")
        if isinstance(s, int):
            status = s
        if isinstance(obj.get("headers"), dict):
            headers = obj["headers"]
    text = raw if isinstance(raw, str) else json.dumps(raw, default=str)
    low = text.lower()
    marker = next((label for token, label in _BLOCK_MARKERS if token in low), "")
    hit = status in (403, 429, 503) or bool(marker)
    if not hit:
        return None
    vendor = detect_vendor(headers, text) or None
    return {
        "blocked": True,
        "status": status,
        "vendor": vendor,
        "marker": marker,
        "next_steps": [
            "record_defense_profile(vendor=..., bypass_failed=[<tier just blocked>])",
            "Change one variable (encoding, header casing, method) instead of replaying the blocked request.",
        ],
    }


