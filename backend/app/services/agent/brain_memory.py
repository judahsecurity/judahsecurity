def observe_response(
    manager_or_brain: Any,
    *,
    method: str = "GET",
    url: str = "",
    status: Any = 0,
    headers: Optional[Dict[str, Any]] = None,
    body: str = "",
) -> Optional[Dict[str, Any]]:
    """Fold one observed response into the brain's defense profile.

    Cheap enough for every exchange: a header scan and a 4 KiB body prefix.
    Stores counts, fixed labels and the request path (no query, no body).
    """
    try:
        reading = classify_response(status, headers, body)
        brain = _brain_dict(manager_or_brain)
        if brain is None:
            brain = manager_or_brain
        profile = _profile_of(brain)
        profile["observed_responses"] = int(profile.get("observed_responses") or 0) + 1
        vendor = reading["vendor"]
        if vendor:
            seen = profile.get("vendors_seen")
            if not isinstance(seen, dict):
                seen = profile["vendors_seen"] = {}
            seen[vendor] = int(seen.get(vendor) or 0) + 1
            if not profile.get("vendor"):
                profile["vendor"] = vendor
        if not reading["blocked"]:
            return reading
        profile["detected"] = True
        profile["blocked_responses"] = int(profile.get("blocked_responses") or 0) + 1
        try:
            path = urlsplit(str(url or "")).path or "/"
        except ValueError:
            path = "/"
        signature = f"{reading['vendor'] or 'unknown'}|{reading['status']}|{reading['marker'] or 'status'}"
        rows = [r for r in (profile.get("block_signatures") or []) if isinstance(r, dict)]
        row = next((r for r in rows if r.get("signature") == signature), None)
        if row is None:
            row = {
                "signature": signature,
                "vendor": reading["vendor"],
                "status": reading["status"],
                "marker": reading["marker"],
                "count": 0,
                "first_seen": _now(),
                "paths": [],
            }
            rows.append(row)
        row["count"] = int(row.get("count") or 0) + 1
        row["last_seen"] = _now()
        row["last_method"] = str(method or "GET").upper()[:10]
        clean_path = _clean(path, 160)
        if clean_path:
            row["paths"] = _union_front(row.get("paths") or [], [clean_path], 5)
        rows.sort(key=lambda r: -(r.get("last_seen") or 0))
        profile["block_signatures"] = rows[:_MAX_SIGNATURES]
        return reading
    except Exception:
        logger.debug("defense observation skipped", exc_info=True)
        return None


def update_defense_profile(
    brain: Any,
    *,
    detected: Optional[bool] = None,
    vendor: str = "",
    blocked_patterns: Optional[Iterable[str]] = None,
    bypass_confirmed: Optional[Iterable[str]] = None,
    bypass_failed: Optional[Iterable[str]] = None,
) -> Dict[str, Any]:
    """Vanguard ``update_waf``: merge agent-reported defense facts."""
    profile = _profile_of(brain)
    if detected is not None:
        profile["detected"] = bool(detected)
    vendor = _clean(vendor, 60).lower()
    if vendor:
        profile["vendor"] = vendor
        profile["detected"] = True if detected is None else bool(detected)
    for key, values, limit in (
        ("blocked_patterns", blocked_patterns, _MAX_PATTERNS),
        ("bypass_confirmed", bypass_confirmed, _MAX_BYPASS),
        ("bypass_failed", bypass_failed, _MAX_BYPASS),
    ):
        if isinstance(values, str):
            values = [values]
        clean = [c for c in (_clean(v) for v in (values or [])) if c]
        if clean:
            profile[key] = _union_front(profile.get(key) or [], clean, limit)
    return profile


def technique_key(endpoint: str, category: str) -> str:
    from app.services.agent.independent_verify import normalized_endpoint

    return f"{normalized_endpoint(endpoint) or '*'}::{str(category or '').strip().lower()[:40]}"


def mark_exhausted(brain: Any, endpoint: str, category: str, technique: str) -> str:
    """Record that ``technique`` was tried and failed for (endpoint, category)."""
    category = str(category or "").strip().lower()
    technique = _clean(technique, 120)
    if not category or not technique:
        return ""
    store = _field(brain, "exhausted_techniques")
    key = technique_key(endpoint, category)
    store[key] = _union_front(store.get(key) or [], [technique], _MAX_TECHNIQUES_PER_KEY)
    if len(store) > _MAX_EXHAUSTED_KEYS:
        for stale in list(store)[: len(store) - _MAX_EXHAUSTED_KEYS]:
            store.pop(stale, None)
    return key


def get_exhausted(brain: Any, endpoint: str, category: str) -> List[str]:
    key = technique_key(endpoint, category)
    local = list(_field(brain, "exhausted_techniques").get(key) or [])
    prior = _prior(brain).get("exhausted_techniques") or {}
    return _union_front(prior.get(key) or [], local, _MAX_TECHNIQUES_PER_KEY)


def add_effective_payload(brain: Any, category: str, payload: str) -> str:
    """Save a payload that worked for ``category`` (most recent first)."""
    category = str(category or "").strip().lower()[:40]
    payload = _clean(payload)
    if not category or not payload:
        return ""
    store = _field(brain, "effective_payloads")
    store[category] = _union_front(store.get(category) or [], [payload], _MAX_PAYLOADS_PER_CATEGORY)
    if len(store) > _MAX_PAYLOAD_CATEGORIES:
        for stale in list(store)[: len(store) - _MAX_PAYLOAD_CATEGORIES]:
            store.pop(stale, None)
    return payload


def _prior(brain: Any) -> Dict[str, Any]:
    value = brain.get("prior_target_memory") if isinstance(brain, dict) else getattr(brain, "prior_target_memory", None)
    return value if isinstance(value, dict) else {}


def attack_memory_view(brain: Any) -> Dict[str, Any]:
    """Structured view for ``get_engagement_brain`` and ``record_defense_profile``."""
    def get(name):
        value = brain.get(name) if isinstance(brain, dict) else getattr(brain, name, None)
        return value if isinstance(value, dict) else {}

    prior = _prior(brain)
    view: Dict[str, Any] = {
        "defense_profile": get("defense_profile"),
        "exhausted_techniques": get("exhausted_techniques"),
        "effective_payloads": get("effective_payloads"),
    }
    if prior:
        view["prior_target_memory"] = prior
    return view


def format_attack_memory_for_prompt(brain: Any) -> str:
    """Compact lines for the brain prompt view / specialist opening."""
    view = attack_memory_view(brain)
    profile = view["defense_profile"]
    lines: List[str] = []
    if profile.get("detected") or profile.get("vendor") or profile.get("blocked_patterns"):
        bits = [f"vendor={profile.get('vendor') or 'unknown'}"]
        if profile.get("blocked_responses"):
            bits.append(f"blocked {profile['blocked_responses']}/{profile.get('observed_responses') or 0} responses")
        lines.append("Defense profile: " + ", ".join(bits))
        if profile.get("blocked_patterns"):
            lines.append("  blocked patterns: " + "; ".join(profile["blocked_patterns"][:8]))
        sigs = [s.get("signature") for s in (profile.get("block_signatures") or [])[:4] if isinstance(s, dict)]
        if sigs:
            lines.append("  block signatures: " + "; ".join(str(s) for s in sigs))
        if profile.get("bypass_confirmed"):
            lines.append("  bypass worked: " + "; ".join(profile["bypass_confirmed"][:5]))
        if profile.get("bypass_failed"):
            lines.append("  bypass failed: " + "; ".join(profile["bypass_failed"][:5]))
    exhausted = view["exhausted_techniques"]
    if exhausted:
        lines.append("Exhausted techniques (skip unless something changed):")
        for key, techniques in list(exhausted.items())[-8:]:
            lines.append(f"  - {key}: {', '.join(techniques[:6])}")
    payloads = view["effective_payloads"]
    if payloads:
        lines.append("Effective payloads by category:")
        for category, items in list(payloads.items())[:6]:
            lines.append(f"  - {category}: {' | '.join(items[:3])}")
    prior = view.get("prior_target_memory") or {}
    if prior:
        p_profile = prior.get("defense_profile") or {}
        p_exhausted = prior.get("exhausted_techniques") or {}
        p_payloads = prior.get("effective_payloads") or {}
        if p_profile or p_exhausted or p_payloads:
            lines.append(
                f"Prior runs on {prior.get('origin') or 'this origin'} (context only, not proof): "
                f"vendor={p_profile.get('vendor') or 'unknown'}, "
                f"{len(p_exhausted)} exhausted endpoint/category pairs, "
                f"{sum(len(v) for v in p_payloads.values())} payloads that worked before."
            )
            for key, techniques in list(p_exhausted.items())[:4]:
                lines.append(f"  prior exhausted {key}: {', '.join(techniques[:4])}")
            for category, items in list(p_payloads.items())[:3]:
                lines.append(f"  prior payload {category}: {' | '.join(items[:2])}")
    return "\n".join(lines)


# ---------------------------------------------------------- cross-run store


def _root() -> Path:
    configured = (os.environ.get("AEGIS_TARGET_MEMORY_DIR") or "").strip()
    return Path(configured) if configured else Path.home() / ".aegis" / "target_memory"


def target_origin(target: str) -> str:
    """``scheme://host[:port]`` for a URL or bare host; empty when unusable."""
    raw = str(target or "").strip()
    if not raw:
        return ""
    try:
        parts = urlsplit(raw if "://" in raw else "https://" + raw)
        host = (parts.hostname or "").lower().rstrip(".")
        if parts.scheme not in ("http", "https") or not host or parts.username or parts.password:
            return ""
        port = parts.port
    except ValueError:
        return ""
    default = 443 if parts.scheme == "https" else 80
    return f"{parts.scheme}://{host}" + (f":{port}" if port and port != default else "")


def _memory_path(organization_id: int, origin: str) -> Path:
    digest = hashlib.sha256(origin.encode()).hexdigest()[:32]
    return _root() / str(int(organization_id)) / f"{digest}.json"


def _sanitize_record(data: Dict[str, Any]) -> Dict[str, Any]:
    """Re-apply bounds and redaction to anything read from or written to disk."""
    profile_in = data.get("defense_profile") if isinstance(data.get("defense_profile"), dict) else {}
    profile: Dict[str, Any] = {}
    vendor = _clean(profile_in.get("vendor"), 60)
    if vendor:
        profile["vendor"] = vendor
    if profile_in.get("detected"):
        profile["detected"] = True
    for key, limit in (("blocked_patterns", _MAX_PATTERNS), ("bypass_confirmed", _MAX_BYPASS),
                       ("bypass_failed", _MAX_BYPASS)):
        clean = [c for c in (_clean(v) for v in (profile_in.get(key) or [])[:limit]) if c]
        if clean:
            profile[key] = clean
    sigs = []
    for row in (profile_in.get("block_signatures") or [])[:_MAX_SIGNATURES]:
        if not isinstance(row, dict):
            continue
        sigs.append({
            "signature": _clean(row.get("signature"), 120),
            "vendor": _clean(row.get("vendor"), 60),
            "status": int(row.get("status") or 0) if str(row.get("status") or "0").isdigit() else 0,
            "marker": _clean(row.get("marker"), 40),
            "count": int(row.get("count") or 0) if str(row.get("count") or "0").isdigit() else 0,
            "paths": [p for p in (_clean(x, 160) for x in (row.get("paths") or [])[:5]) if p],
        })
    if sigs:
        profile["block_signatures"] = sigs
    exhausted: Dict[str, List[str]] = {}
    for key, techniques in list((data.get("exhausted_techniques") or {}).items())[:_MAX_EXHAUSTED_KEYS]:
        clean_key = _clean(key, 300)
        clean = [c for c in (_clean(t, 120) for t in (techniques or [])[:_MAX_TECHNIQUES_PER_KEY]) if c]
        if clean_key and clean:
            exhausted[clean_key] = clean
    payloads: Dict[str, List[str]] = {}
    for category, items in list((data.get("effective_payloads") or {}).items())[:_MAX_PAYLOAD_CATEGORIES]:
        clean_cat = _clean(category, 40)
        clean = [c for c in (_clean(p) for p in (items or [])[:_MAX_PAYLOADS_PER_CATEGORY]) if c]
        if clean_cat and clean:
            payloads[clean_cat] = clean
    return {"defense_profile": profile, "exhausted_techniques": exhausted, "effective_payloads": payloads}


def _read(path: Path) -> Dict[str, Any]:
    try:
        if not path.is_file() or path.stat().st_size > _MAX_FILE_BYTES:
            return {}
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except Exception:
        logger.debug("target memory read skipped", exc_info=True)
        return {}


def load_target_memory(organization_id: Optional[int], target: str) -> Dict[str, Any]:
    """Prior-run attack memory for this organization and target origin, or {}."""
    origin = target_origin(target)
    if not organization_id or not origin:
        return {}
    data = _read(_memory_path(int(organization_id), origin))
    # The org directory already isolates tenants; the stored keys are checked
    # as well so a misplaced file is never served to another organization.
    if not data or data.get("organization_id") != int(organization_id) or data.get("origin") != origin:
        return {}
    record = _sanitize_record(data)
    if not any(record.values()):
        return {}
    return {
        **record,
        "origin": origin,
        "saved_at": data.get("saved_at"),
        "runs": int(data.get("runs") or 0),
        "source": "cross_run_memory",
        "proof": False,
        "note": PRIOR_MEMORY_NOTE,
    }


def _merge(old: Dict[str, Any], new: Dict[str, Any]) -> Dict[str, Any]:
    op, np = old.get("defense_profile") or {}, new.get("defense_profile") or {}
    profile: Dict[str, Any] = {}
    if np.get("vendor") or op.get("vendor"):
        profile["vendor"] = np.get("vendor") or op.get("vendor")
    if np.get("detected") or op.get("detected"):
        profile["detected"] = True
    for key, limit in (("blocked_patterns", _MAX_PATTERNS), ("bypass_confirmed", _MAX_BYPASS),
                       ("bypass_failed", _MAX_BYPASS)):
        merged = _union_front(op.get(key) or [], np.get(key) or [], limit)
        if merged:
            profile[key] = merged
    sigs = {s["signature"]: s for s in (op.get("block_signatures") or []) if s.get("signature")}
    for s in np.get("block_signatures") or []:
        if s.get("signature"):
            sigs[s["signature"]] = s
    if sigs:
        profile["block_signatures"] = list(sigs.values())[-_MAX_SIGNATURES:]
    exhausted = {k: list(v) for k, v in (old.get("exhausted_techniques") or {}).items()}
    for key, techniques in (new.get("exhausted_techniques") or {}).items():
        exhausted[key] = _union_front(exhausted.get(key) or [], techniques, _MAX_TECHNIQUES_PER_KEY)
    payloads = {k: list(v) for k, v in (old.get("effective_payloads") or {}).items()}
    for category, items in (new.get("effective_payloads") or {}).items():
        payloads[category] = _union_front(payloads.get(category) or [], items, _MAX_PAYLOADS_PER_CATEGORY)
    return {
        "defense_profile": profile,
        "exhausted_techniques": dict(list(exhausted.items())[-_MAX_EXHAUSTED_KEYS:]),
        "effective_payloads": dict(list(payloads.items())[-_MAX_PAYLOAD_CATEGORIES:]),
    }


def save_target_memory(
    organization_id: Optional[int],
    target: str,
    brain: Any,
    *,
    session_id: str = "",
) -> bool:
    """Merge this run's attack memory into the per-org, per-origin record."""
    origin = target_origin(target)
    if not organization_id or not origin or not brain:
        return False
    view = attack_memory_view(brain)
    current = _sanitize_record(view)
    if not any(current.values()):
        return False
    path = _memory_path(int(organization_id), origin)
    existing = _read(path)
    if existing and (existing.get("organization_id") != int(organization_id) or existing.get("origin") != origin):
        existing = {}
    merged = _sanitize_record(_merge(_sanitize_record(existing) if existing else {}, current))
    sessions = [s for s in (existing.get("sessions") or []) if isinstance(s, str)]
    session_ref = hashlib.sha256(f"{organization_id}:{session_id}".encode()).hexdigest()[:16] if session_id else ""
    runs = int(existing.get("runs") or 0)
    if session_ref and session_ref not in sessions:
        sessions.append(session_ref)
        runs += 1
    payload = {
        "schema_version": 1,
        "organization_id": int(organization_id),
        "origin": origin,
        "saved_at": _now(),
        "runs": max(runs, 1),
        "sessions": sessions[-50:],
        **merged,
    }
    encoded = json.dumps(payload, separators=(",", ":"), default=str).encode()
    if len(encoded) > _MAX_FILE_BYTES:
        logger.warning("target memory exceeds %d bytes; prior record retained", _MAX_FILE_BYTES)
        return False
    try:
        directory = path.parent
        directory.mkdir(parents=True, exist_ok=True, mode=0o700)
        os.chmod(_root(), 0o700)
        os.chmod(directory, 0o700)
        temporary = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
        fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        try:
            with os.fdopen(fd, "wb") as stream:
                stream.write(encoded)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, path)
            os.chmod(path, 0o600)
        finally:
            try:
                temporary.unlink()
            except FileNotFoundError:
                pass
        return True
    except Exception:
        logger.debug("target memory save skipped", exc_info=True)
        return False


def attach_prior_memory(brain: Optional[Dict[str, Any]], organization_id: Optional[int],
                        target: str) -> Optional[Dict[str, Any]]:
    """Return ``brain`` (dict) with ``prior_target_memory`` set when a record exists."""
    memory = load_target_memory(organization_id, target)
    if not memory:
        return brain
    out = dict(brain or {})
    if not out.get("target"):
        out["target"] = str(target or "")
    out["prior_target_memory"] = memory
    return out


def purge_target_memory(organization_id: int) -> None:
    """Remove an organization's cross-run attack memory."""
    import shutil

    directory = _root() / str(int(organization_id))
    if directory.is_dir():
        shutil.rmtree(directory, ignore_errors=True)


