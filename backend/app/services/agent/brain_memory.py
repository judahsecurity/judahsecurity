def record_corroboration(candidate: Any, specialist: str) -> bool:
    """Note that another specialist independently reported the same root cause.

    Triage context only: verdicts and publication never read this field.
    """
    name = str(specialist or "").strip()[:80]
    original = str(getattr(candidate, "specialist", "") or "")
    if not name or not original or name == original:
        return False
    current = list(getattr(candidate, "corroborated_by", None) or [])
    if name in current:
        return False
    candidate.corroborated_by = (current + [name])[-10:]
    return True

