"""Attack memory on the engagement brain: defenses, exhausted techniques, payloads.

Ported from Aegis Vanguard (``agent/brain.py`` WAF profile / exhausted
techniques / effective payloads, ``agent/distiller.py`` ``read_defense``).

Three pieces live on the session brain (``EngagementBrain`` fields):

* ``defense_profile`` - WAF vendor, blocked patterns, block signatures and
  bypass tiers. Fed automatically from every ``_http_exchange`` response
  (header/status/body-prefix scan, no body is stored) and by
  ``record_defense_profile``.
* ``exhausted_techniques`` - ``"<endpoint>::<category>" -> [technique]``.
* ``effective_payloads`` - ``category -> [payload]`` (most recent first).

Cross-run memory keeps those three per organization and target origin under
``AEGIS_TARGET_MEMORY_DIR`` (default ``~/.aegis/target_memory``), one 0600
file per ``<org_id>/<sha256(origin)>.json`` written by atomic replace, the
same pattern as ``run_snapshot.py``. Palace drawers are free text keyed by
host and the run snapshot is keyed by session, so neither fits a merged,
structured per-origin record. A loaded record is attached as
``prior_target_memory`` and is prior context only: it never counts as proof.
"""

