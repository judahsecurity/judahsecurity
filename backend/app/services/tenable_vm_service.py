def severity_from_cvss(score: Optional[float]) -> Severity:
    if score is None:
        return Severity.INFO
    if score >= 9.0:
        return Severity.CRITICAL
    if score >= 7.0:
        return Severity.HIGH
    if score >= 4.0:
        return Severity.MEDIUM
    if score >= 0.1:
        return Severity.LOW
    return Severity.INFO


def _float(value: Any) -> Optional[float]:
    try:
        return float(value) if value not in (None, "") else None
    except (TypeError, ValueError):
        return None


def cvss_rating(plugin: Dict[str, Any]) -> Tuple[Optional[float], Severity]:
    """CVSSv3 temporal score, else CVSSv3 base score, mapped to severity.

    Findings with no CVSSv3 score at all fall back to Tenable's own severity
    label so an unscored High is not silently imported as Info.
    """
    score = _float(plugin.get("cvss3_temporal_score"))
    if score is None:
        score = _float(plugin.get("cvss3_base_score"))
    if score is not None:
        return score, severity_from_cvss(score)
    label = str(plugin.get("risk_factor") or "").strip().lower()
    fallback = {
        "critical": Severity.CRITICAL, "high": Severity.HIGH,
        "medium": Severity.MEDIUM, "low": Severity.LOW,
    }.get(label, Severity.INFO)
    return None, fallback


def _cvss_vector(plugin: Dict[str, Any]) -> Optional[str]:
    vector = plugin.get("cvss3_vector")
    if isinstance(vector, dict):
        vector = vector.get("raw")
    return str(vector)[:100] if vector else None


def _is_internal_hostname(name: str) -> bool:
    host = name.strip().lower().rstrip(".")
    if not host or "." not in host:
        return True
    padded = f".{host}"
    return padded.endswith(_INTERNAL_SUFFIXES) or padded.endswith(_CLOUD_PROVIDER_SUFFIXES)


def _is_ip_literal(value: str) -> bool:
    try:
        ipaddress.ip_address(value)
        return True
    except ValueError:
        return False


class _AddressFilter:
    """Skips private, internal, and cloud-provider addresses."""

    def __init__(self, db: Optional[Session], organization_id: int,
                 classify: Optional[Callable[[str], Any]] = None) -> None:
        self.organization_id = organization_id
        if classify is None:
            from app.services.ip_classifier_service import IPClassifierService

            classifier = IPClassifierService(db)
            classify = lambda ip: classifier.classify(ip, organization_id)  # noqa: E731
        self._classify = classify
        self._cache: Dict[str, bool] = {}

    def public_ipv4(self, value: str) -> bool:
        ip = (value or "").strip()
        if ip in self._cache:
            return self._cache[ip]
        try:
            parsed = ipaddress.ip_address(ip)
        except ValueError:
            self._cache[ip] = False
            return False
        ok = parsed.version == 4 and parsed.is_global
        if ok:
            hosting = getattr(self._classify(ip), "hosting_type", "unknown")
            ok = hosting not in _SKIPPED_HOSTING_TYPES
        self._cache[ip] = ok
        return ok

    def identity(self, fqdns: List[Any], ipv4s: List[Any]) -> Optional[Tuple[str, AssetType]]:
        for fqdn in fqdns or []:
            name = str(fqdn or "").strip().lower().rstrip(".")
            if not name:
                continue
            if _is_ip_literal(name):
                if self.public_ipv4(name):
                    return name, AssetType.IP_ADDRESS
                continue
            if not _is_internal_hostname(name):
                return name, (AssetType.DOMAIN if name.count(".") == 1 else AssetType.SUBDOMAIN)
        for ip in ipv4s or []:
            value = str(ip or "").strip()
            if value and self.public_ipv4(value):
                return value, AssetType.IP_ADDRESS
        return None


def _as_list(value: Any) -> List[Any]:
    if value is None or value == "":
        return []
    return list(value) if isinstance(value, (list, tuple)) else [value]


def _parse_datetime(value: Any) -> Optional[datetime]:
    if not value:
        return None
    try:
        parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except (TypeError, ValueError):
        return None
    if parsed.tzinfo is not None:
        parsed = parsed.astimezone(timezone.utc).replace(tzinfo=None)
    return parsed


def record_identifiers(record: Dict[str, Any]) -> List[Identifier]:
    """IDs carried by a Tenable asset record (asset export or a finding's
    ``asset`` block), strongest first. Works without a Tenable UUID."""
    ids: List[Optional[Identifier]] = []
    for arn in _as_list(record.get("aws_ec2_instance_arn")):
        ids.extend(aws_ids(arn))
    for instance in _as_list(record.get("aws_ec2_instance_id")):
        ids.extend(aws_ids(instance))
    for resource_id in _as_list(record.get("azure_resource_id")):
        ids.extend(azure_ids(resource_id=resource_id))
    for vm_id in _as_list(record.get("azure_vm_id")):
        ids.extend(azure_ids(vm_id=vm_id))
    for instance in _as_list(record.get("gcp_instance_id")):
        ids.extend(gcp_ids(instance_id=instance))
    for bios in _as_list(record.get("bios_uuid")):
        ids.append(bios_id(bios))
    for mac in _as_list(record.get("mac_addresses")) + _as_list(record.get("mac_address")):
        ids.append(mac_id(mac))
    ids.append(record_id(TENABLE_ASSET, record.get("id") or record.get("uuid")))
    for agent in _as_list(record.get("agent_uuid")):
        ids.append(record_id(TENABLE_AGENT, agent))
    return unique(ids)


def _has_public_ipv4(ipv4s: List[Any]) -> bool:
    for ip in ipv4s:
        try:
            parsed = ipaddress.ip_address(str(ip).strip())
        except ValueError:
            continue
        if parsed.version == 4 and parsed.is_global:
            return True
    return False


def _detector_for(finding: Dict[str, Any]) -> str:
    """Agent / credentialed findings are invisible to an external attacker."""
    asset = finding.get("asset") or {}
    plugin = finding.get("plugin") or {}
    if asset.get("agent_uuid"):
        return "tenable_agent"
    if "local security checks" in str(plugin.get("family") or "").lower():
        return "tenable_credentialed"
    return DISCOVERY_SOURCE


def build_proof(finding: Dict[str, Any]) -> str:
    plugin = finding.get("plugin") or {}
    port = finding.get("port") or {}
    lines: List[str] = []
    if port.get("port"):
        service = f" ({port['service']})" if port.get("service") else ""
        lines.append(f"Service: {port.get('port')}/{str(port.get('protocol') or 'tcp').lower()}{service}")
    cves = _as_list(plugin.get("cve"))
    if cves:
        lines.append(f"CVEs: {', '.join(str(c) for c in cves)}")
    for label, key in (("CVSSv3 base score", "cvss3_base_score"), ("CVSSv3 temporal score", "cvss3_temporal_score")):
        if plugin.get(key) not in (None, ""):
            lines.append(f"{label}: {plugin.get(key)}")
    vector = _cvss_vector(plugin)
    if vector:
        lines.append(f"CVSSv3 vector: {vector}")
    lines.append(f"Tenable plugin: {plugin.get('id')} — {plugin.get('name') or ''}".rstrip(" —"))
    output = finding.get("output")
    if output:
        lines.append("")
        lines.append("Plugin output:")
        lines.append(str(output)[:20000])
    return "\n".join(lines)


def build_definition(plugin: Dict[str, Any]) -> str:
    parts = [str(plugin.get("synopsis") or "").strip(), str(plugin.get("description") or "").strip()]
    return "\n\n".join(p for p in parts if p) or str(plugin.get("name") or "")


