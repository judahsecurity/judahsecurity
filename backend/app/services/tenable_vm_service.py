class TenableApiError(RuntimeError):
    """A safe, user-displayable Tenable API error."""


def _validate_tenable_url(value: str) -> str:
    raw = (value or "").strip().rstrip("/") or DEFAULT_TENABLE_URL
    parsed = urlparse(raw)
    host = (parsed.hostname or "").lower()
    if parsed.scheme != "https" or not host or parsed.username or parsed.password or parsed.port:
        raise TenableApiError("Tenable VM URL must be an HTTPS URL without credentials or a port.")
    if host not in ALLOWED_HOSTS and not host.endswith(".tenable.com"):
        raise TenableApiError("Tenable VM URL must be a tenable.com host, e.g. https://cloud.tenable.com.")
    if parsed.path not in ("", "/"):
        raise TenableApiError("Tenable VM URL must not include a path, e.g. https://cloud.tenable.com.")
    return f"https://{host}"


class TenableClient:
    """Minimal Tenable.io export API client (API-key auth)."""

    POLL_INTERVAL_SECONDS = 5.0
    MAX_EXPORT_WAIT_SECONDS = 60 * 60
    ASSET_CHUNK_SIZE = 1000
    VULN_ASSETS_PER_CHUNK = 500

    def __init__(
        self,
        base_url: str,
        access_key: str,
        secret_key: str,
        *,
        transport: Optional[httpx.AsyncBaseTransport] = None,
        poll_interval: Optional[float] = None,
    ) -> None:
        if not access_key or not secret_key:
            raise TenableApiError("Tenable Access Key and Secret Key are required.")
        self.base_url = _validate_tenable_url(base_url)
        self._headers = {
            "X-ApiKeys": f"accessKey={access_key};secretKey={secret_key}",
            "Accept": "application/json",
            "Content-Type": "application/json",
            "User-Agent": "Integration/1.0 (Judah Security; ASM; Build/1.0)",
        }
        self._transport = transport
        self.poll_interval = self.POLL_INTERVAL_SECONDS if poll_interval is None else poll_interval

    async def _request(self, method: str, path: str, json: Optional[Dict[str, Any]] = None) -> Any:
        url = f"{self.base_url}{path}"
        for attempt in range(5):
            try:
                async with httpx.AsyncClient(timeout=120.0, transport=self._transport) as client:
                    response = await client.request(method, url, json=json, headers=self._headers)
            except httpx.HTTPError as exc:
                if attempt == 4:
                    raise TenableApiError(f"Could not reach Tenable VM: {exc.__class__.__name__}") from exc
                await asyncio.sleep(min(2**attempt, 30) if self.poll_interval else 0)
                continue
            if response.status_code in (429, 500, 502, 503, 504) and attempt < 4:
                retry_after = response.headers.get("Retry-After")
                try:
                    delay = float(retry_after) if retry_after else float(2**attempt)
                except ValueError:
                    delay = float(2**attempt)
                await asyncio.sleep(min(delay, 60.0) if self.poll_interval else 0)
                continue
            if response.status_code == 401:
                raise TenableApiError("Tenable VM rejected the API keys (HTTP 401); check the Access Key and Secret Key.")
            if response.status_code == 403:
                raise TenableApiError(
                    "Tenable VM denied the request (HTTP 403); give the service account the "
                    "Can View permission on All Assets."
                )
            if response.status_code >= 400:
                raise TenableApiError(f"Tenable VM request {method} {path} failed (HTTP {response.status_code}).")
            if not response.content:
                return {}
            try:
                return response.json()
            except ValueError as exc:
                raise TenableApiError("Tenable VM returned an invalid JSON response.") from exc
        raise TenableApiError("Tenable VM request failed after retries.")

    # ── Export lifecycle ────────────────────────────────────────────────────

    async def start_export(self, kind: str, body: Dict[str, Any]) -> str:
        payload = await self._request("POST", f"/{kind}/export", json=body)
        export_uuid = (payload or {}).get("export_uuid")
        if not export_uuid:
            raise TenableApiError(f"Tenable VM did not return an export id for the {kind} export.")
        return str(export_uuid)

    async def cancel_export(self, kind: str, export_uuid: str) -> None:
        try:
            await self._request("POST", f"/{kind}/export/{export_uuid}/cancel")
        except TenableApiError as exc:
            logger.debug("Tenable %s export %s cancel failed: %s", kind, export_uuid, exc)

    async def collect_export(self, kind: str, export_uuid: str) -> List[Dict[str, Any]]:
        """Poll an export and download every chunk as it becomes available."""
        records: List[Dict[str, Any]] = []
        downloaded: set[int] = set()
        deadline = time.monotonic() + self.MAX_EXPORT_WAIT_SECONDS
        while True:
            status = await self._request("GET", f"/{kind}/export/{export_uuid}/status")
            state = str((status or {}).get("status") or "").upper()
            if state in {"ERROR", "CANCELLED"}:
                raise TenableApiError(f"Tenable VM {kind} export ended with status {state}.")
            for chunk_id in sorted(int(c) for c in (status.get("chunks_available") or [])):
                if chunk_id in downloaded:
                    continue
                chunk = await self._request("GET", f"/{kind}/export/{export_uuid}/chunks/{chunk_id}")
                if isinstance(chunk, list):
                    records.extend(item for item in chunk if isinstance(item, dict))
                downloaded.add(chunk_id)
            if state == "FINISHED":
                return records
            if time.monotonic() > deadline:
                await self.cancel_export(kind, export_uuid)
                raise TenableApiError(f"Tenable VM {kind} export did not finish in time.")
            await asyncio.sleep(self.poll_interval)

    @staticmethod
    def asset_export_body(since_epoch: int) -> Dict[str, Any]:
        return {"chunk_size": TenableClient.ASSET_CHUNK_SIZE, "filters": {"last_assessed": since_epoch}}

    @staticmethod
    def vuln_export_body(since_epoch: int) -> Dict[str, Any]:
        return {
            "num_assets": TenableClient.VULN_ASSETS_PER_CHUNK,
            "filters": {
                "severity": IMPORTED_SEVERITIES,
                "state": IMPORTED_STATES,
                "last_found": since_epoch,
            },
        }

    @staticmethod
    def fixed_vuln_export_body(since_epoch: int) -> Dict[str, Any]:
        return {
            "num_assets": TenableClient.VULN_ASSETS_PER_CHUNK,
            "filters": {
                "severity": IMPORTED_SEVERITIES,
                "state": ["FIXED"],
                "last_fixed": since_epoch,
            },
        }

    async def export_assets(self, since_epoch: int) -> List[Dict[str, Any]]:
        export_uuid = await self.start_export("assets", self.asset_export_body(since_epoch))
        return await self.collect_export("assets", export_uuid)

    async def export_vulns(self, since_epoch: int) -> List[Dict[str, Any]]:
        export_uuid = await self.start_export("vulns", self.vuln_export_body(since_epoch))
        return await self.collect_export("vulns", export_uuid)

    async def export_fixed_vulns(self, since_epoch: int) -> List[Dict[str, Any]]:
        export_uuid = await self.start_export("vulns", self.fixed_vuln_export_body(since_epoch))
        return await self.collect_export("vulns", export_uuid)


def _since_epoch(days: int = LOOKBACK_DAYS) -> int:
    return int(time.time()) - days * 86400


async def test_connection(
    base_url: str,
    access_key: str,
    secret_key: str,
    *,
    transport: Optional[httpx.AsyncBaseTransport] = None,
) -> Dict[str, Any]:
    """Validate keys by requesting an asset export and a vulnerability export.

    Both test exports use a "since now" filter so they are near-empty, and
    are cancelled immediately so they don't hold Tenable's export slots.
    """
    result = {"ok": False, "message": "", "assets_export_ok": False, "vulns_export_ok": False}
    try:
        client = TenableClient(base_url, access_key, secret_key, transport=transport)
        now = int(time.time())
        asset_uuid = await client.start_export("assets", client.asset_export_body(now))
        result["assets_export_ok"] = True
        await client.cancel_export("assets", asset_uuid)
        vuln_uuid = await client.start_export("vulns", client.vuln_export_body(now))
        result["vulns_export_ok"] = True
        await client.cancel_export("vulns", vuln_uuid)
    except TenableApiError as exc:
        failed = "vulnerability" if result["assets_export_ok"] else "asset"
        result["message"] = f"The {failed} export request failed: {exc}"
        return result
    result["ok"] = True
    result["message"] = "Connected to Tenable VM and verified asset and vulnerability export access."
    return result


