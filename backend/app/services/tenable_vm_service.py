class TenableImporter:
    def __init__(self, db: Session, organization_id: int,
                 address_filter: Optional[_AddressFilter] = None) -> None:
        self.db = db
        self.org_id = organization_id
        self.addresses = address_filter or _AddressFilter(db, organization_id)
        self.stats = _Stats()
        self.resolver = AssetIdentityResolver(db, organization_id, DISCOVERY_SOURCE)
        self._by_uuid: Dict[str, Asset] = {}
        self._touched_assets: set[int] = set()

    # Assets ------------------------------------------------------------------

    def _by_value(self, value: str) -> Optional[Asset]:
        return self.db.query(Asset).filter(
            Asset.organization_id == self.org_id, Asset.value == value
        ).first()

    def _resolve_record(self, record: Dict[str, Any], identity: Optional[Tuple[str, AssetType]],
                        create: bool = True) -> Optional[Asset]:
        """Match ``record`` to an asset by its own IDs, then its public name.

        With ``create`` the asset is created when nothing matches, and every
        ID in the record is registered on the result.
        """
        uuid = str(record.get("id") or record.get("uuid") or "").lower()
        if uuid and uuid in self._by_uuid:
            return self._by_uuid[uuid]
        ids = record_identifiers(record)
        cloud = primary_cloud_id(ids)
        # A cloud ID makes the asset importable even when its only public
        # address is a (skipped, ephemeral) cloud IP.
        cloud_importable = cloud is not None and _has_public_ipv4(_as_list(record.get("ipv4s")))
        resolution = self.resolver.resolve(
            ids, fallback=(lambda: self._by_value(identity[0])) if identity else None
        )
        asset = resolution.asset
        if asset is None:
            if not create:
                return None
            if identity is not None and not resolution.conflict:
                value, asset_type = identity
            elif cloud is not None and (cloud_importable or identity is not None):
                # Either no public name, or the name already belongs to a
                # different machine: name this one by its provider ID.
                value, asset_type = cloud.value, AssetType.CLOUD_RESOURCE
            else:
                return None
        else:
            value, asset_type = asset.value, asset.asset_type
            if resolution.duplicates and create:
                self.stats.assets_merged += self.resolver.merge(asset, resolution.duplicates)
                for key, cached in list(self._by_uuid.items()):
                    if sa_inspect(cached).was_deleted:
                        self._by_uuid[key] = asset
        if not create:
            return asset
        asset = self._upsert_asset(value, asset_type, record, asset, ids)
        self.resolver.attach(asset, ids)
        if uuid:
            self._by_uuid[uuid] = asset
        return asset

    def _upsert_asset(self, value: str, asset_type: AssetType, source: Dict[str, Any],
                      asset: Optional[Asset] = None, ids: Optional[List[Identifier]] = None) -> Asset:
        ipv4s = [str(ip) for ip in _as_list(source.get("ipv4s")) if self.addresses.public_ipv4(str(ip))]
        operating_systems = [str(o) for o in _as_list(source.get("operating_systems")) if o]
        tenable_meta = {
            "asset_uuid": source.get("id") or source.get("uuid"),
            "fqdns": _as_list(source.get("fqdns"))[:50],
            "ipv4s": _as_list(source.get("ipv4s"))[:50],
            "hostnames": _as_list(source.get("hostnames"))[:50],
            "operating_systems": operating_systems[:10],
            "network_name": source.get("network_name"),
            "has_agent": bool(source.get("has_agent") or source.get("agent_uuid")),
            "last_assessed": source.get("last_assessed") or source.get("last_scan_time"),
            "last_seen": source.get("last_seen"),
            "cloud_ids": [
                {"namespace": i.namespace, "value": i.value}
                for i in (ids or []) if i.namespace in CLOUD_NAMESPACES
            ],
            "aws_owner_id": source.get("aws_owner_id"),
            "aws_region": source.get("aws_region"),
            "azure_subscription_id": source.get("azure_subscription_id"),
            "gcp_project_id": source.get("gcp_project_id"),
            "gcp_zone": source.get("gcp_zone"),
        }
        tenable_meta = {k: v for k, v in tenable_meta.items() if v not in (None, [], "")}
        is_new = asset is None
        if is_new:
            asset = Asset(
                name=value[:255],
                asset_type=asset_type,
                value=value[:500],
                organization_id=self.org_id,
                status=AssetStatus.DISCOVERED,
                discovery_source=DISCOVERY_SOURCE,
                association_reason="Asset assessed by the organization's Tenable Vulnerability Management",
                association_confidence=90,
                tags=["source:tenable"],
                metadata_={"tenable": tenable_meta},
                is_public=True,
            )
            if asset_type == AssetType.CLOUD_RESOURCE:
                asset.hosting_type = "cloud"
                asset.is_ephemeral_ip = True
                public = [str(ip) for ip in _as_list(source.get("ipv4s")) if _has_public_ipv4([ip])]
                asset.ip_addresses = public
                asset.ip_address = public[0] if public else None
                asset.name = str((_as_list(source.get("hostnames")) or [value])[0])[:255]
            elif asset_type == AssetType.IP_ADDRESS:
                asset.ip_address = value
                asset.ip_addresses = [value]
            elif ipv4s:
                asset.ip_address = ipv4s[0]
                asset.ip_addresses = ipv4s
            if operating_systems:
                asset.operating_system = operating_systems[0][:200]
            self.db.add(asset)
            self.db.flush()
            self.stats.assets_created += 1
        else:
            metadata = dict(asset.metadata_ or {})
            merged = dict(metadata.get("tenable") or {})
            merged.update(tenable_meta)
            metadata["tenable"] = merged
            asset.metadata_ = metadata
            asset.last_seen = datetime.utcnow()
            if asset.status == AssetStatus.INACTIVE and asset.discovery_source == DISCOVERY_SOURCE:
                asset.status = AssetStatus.DISCOVERED
            if operating_systems and not asset.operating_system:
                asset.operating_system = operating_systems[0][:200]
            if ipv4s and asset.asset_type != AssetType.IP_ADDRESS:
                asset.ip_addresses = sorted(set(asset.ip_addresses or []) | set(ipv4s))
                asset.ip_address = asset.ip_address or ipv4s[0]
            tags = list(asset.tags or [])
            if "source:tenable" not in tags:
                asset.tags = tags + ["source:tenable"]
            if asset.id not in self._touched_assets:
                self.stats.assets_updated += 1
        self._touched_assets.add(asset.id)
        return asset

    def import_assets(self, records: List[Dict[str, Any]]) -> None:
        for record in records:
            self.stats.assets_seen += 1
            if record.get("deleted_at") or record.get("terminated_at"):
                self.stats.assets_skipped += 1
                continue
            identity = self.addresses.identity(_as_list(record.get("fqdns")), _as_list(record.get("ipv4s")))
            if self._resolve_record(record, identity) is None:
                self.stats.assets_skipped += 1

    # Ports -------------------------------------------------------------------

    @staticmethod
    def _port_key(port_info: Dict[str, Any]) -> Optional[Tuple[int, Protocol]]:
        try:
            number = int(port_info.get("port") or 0)
        except (TypeError, ValueError):
            return None
        if not 0 < number < 65536:
            return None
        try:
            protocol = Protocol(str(port_info.get("protocol") or "tcp").lower())
        except ValueError:
            protocol = Protocol.TCP
        return number, protocol

    @staticmethod
    def _template_id(plugin: Dict[str, Any], port_key: Optional[Tuple[int, Protocol]]) -> str:
        suffix = f"{port_key[0]}/{port_key[1].value}" if port_key else "host"
        return f"{TEMPLATE_PREFIX}{plugin.get('id')}:{suffix}"[:255]

    def _upsert_port(self, asset: Asset, port_info: Dict[str, Any]) -> Optional[PortService]:
        key = self._port_key(port_info)
        if key is None:
            return None
        number, protocol = key
        port = self.db.query(PortService).filter(
            PortService.asset_id == asset.id,
            PortService.port == number,
            PortService.protocol == protocol,
        ).first()
        service = str(port_info.get("service") or "").strip() or None
        if port is None:
            port = PortService(
                asset_id=asset.id,
                port=number,
                protocol=protocol,
                service_name=(service[:100] if service else None),
                state=PortState.OPEN,
                discovered_by=DISCOVERY_SOURCE,
                scanned_ip=asset.ip_address,
                first_seen=datetime.utcnow(),
                last_seen=datetime.utcnow(),
            )
            self.db.add(port)
            self.db.flush()
            self.stats.ports_created += 1
        else:
            port.last_seen = datetime.utcnow()
            if service and not port.service_name:
                port.service_name = service[:100]
        return port

    # Vulnerabilities ---------------------------------------------------------

    @staticmethod
    def _finding_record(finding: Dict[str, Any]) -> Dict[str, Any]:
        """A finding's ``asset`` block in asset-export shape."""
        source = finding.get("asset") or {}
        return {
            **source,
            "id": source.get("uuid") or None,
            "fqdns": _as_list(source.get("fqdn")),
            "ipv4s": _as_list(source.get("ipv4")),
            "hostnames": _as_list(source.get("hostname")),
            "operating_systems": _as_list(source.get("operating_system")),
            "network_name": source.get("network_id"),
        }

    def _finding_identity(self, record: Dict[str, Any]) -> Optional[Tuple[str, AssetType]]:
        return self.addresses.identity(record["fqdns"] + record["hostnames"], record["ipv4s"])

    def _asset_for_finding(self, finding: Dict[str, Any], create: bool = True) -> Optional[Asset]:
        record = self._finding_record(finding)
        return self._resolve_record(record, self._finding_identity(record), create=create)

    def import_vulnerabilities(self, findings: List[Dict[str, Any]]) -> None:
        for finding in findings:
            self.stats.vulns_seen += 1
            state = str(finding.get("state") or "OPEN").upper()
            plugin = finding.get("plugin") or {}
            if state not in IMPORTED_STATES or not plugin.get("id"):
                self.stats.vulns_skipped += 1
                continue
            asset = self._asset_for_finding(finding)
            if asset is None:
                self.stats.vulns_skipped += 1
                continue
            self._upsert_vulnerability(asset, finding)

    def _upsert_vulnerability(self, asset: Asset, finding: Dict[str, Any]) -> None:
        plugin = finding.get("plugin") or {}
        port_info = finding.get("port") or {}
        port = self._upsert_port(asset, port_info)
        template_id = self._template_id(plugin, (port.port, port.protocol) if port else None)

        score, severity = cvss_rating(plugin)
        cves = [str(c).upper() for c in _as_list(plugin.get("cve")) if c]
        references = [str(r) for r in _as_list(plugin.get("see_also")) if r][:50]
        title = str(plugin.get("name") or f"Tenable plugin {plugin.get('id')}")[:500]
        if port:
            service = f" ({port.service_name})" if port.service_name else ""
            affected = f"{port.port}/{port.protocol.value}{service}"
        else:
            affected = None
        metadata = {
            "source": DISCOVERY_SOURCE,
            "tenable_state": str(finding.get("state") or "").upper(),
            "tenable_severity": finding.get("severity"),
            "tenable_asset_uuid": (finding.get("asset") or {}).get("uuid"),
            "plugin_id": plugin.get("id"),
            "plugin_family": plugin.get("family"),
            "cves": cves,
            "cvss3_base_score": plugin.get("cvss3_base_score"),
            "cvss3_temporal_score": plugin.get("cvss3_temporal_score"),
            "cvss3_vector": _cvss_vector(plugin),
            "vpr_score": (plugin.get("vpr") or {}).get("score") if isinstance(plugin.get("vpr"), dict) else None,
            "exploit_available": plugin.get("exploit_available"),
            "port": port.port if port else None,
            "protocol": port.protocol.value if port else None,
            "port_service_id": port.id if port else None,
            "service": port_info.get("service"),
        }
        fields = dict(
            title=title,
            description=build_definition(plugin),
            severity=severity,
            cvss_score=score,
            cvss_vector=_cvss_vector(plugin),
            cve_id=cves[0][:50] if cves else None,
            references=references,
            remediation=plugin.get("solution"),
            evidence=build_proof(finding),
            affected_component=affected,
            detected_by=_detector_for(finding),
            last_detected=_parse_datetime(finding.get("last_found")) or datetime.utcnow(),
            metadata_=metadata,
        )
        existing = self.db.query(Vulnerability).filter(
            Vulnerability.asset_id == asset.id,
            Vulnerability.template_id == template_id,
        ).first()
        if existing:
            for key, value in fields.items():
                setattr(existing, key, value)
            if existing.status == VulnerabilityStatus.RESOLVED:
                existing.status = VulnerabilityStatus.OPEN
                existing.resolved_at = None
            self.stats.vulns_updated += 1
            return
        self.db.add(Vulnerability(
            **fields,
            asset_id=asset.id,
            template_id=template_id,
            status=VulnerabilityStatus.OPEN,
            first_detected=_parse_datetime(finding.get("first_found")) or datetime.utcnow(),
            detection_confidence="version_only",
            tags=["source:tenable"],
        ))
        self.stats.vulns_created += 1


# Analyst decisions that a Tenable "fixed" state must not overwrite.
_RESOLVABLE_STATUSES = (VulnerabilityStatus.OPEN, VulnerabilityStatus.IN_PROGRESS)


def _resolve_fixed(importer: "TenableImporter", findings: List[Dict[str, Any]]) -> None:
    """Close findings Tenable now reports as FIXED. Never creates anything."""
    for finding in findings:
        plugin = finding.get("plugin") or {}
        if not plugin.get("id"):
            continue
        asset = importer._asset_for_finding(finding, create=False)
        if asset is None:
            continue
        template_id = importer._template_id(plugin, importer._port_key(finding.get("port") or {}))
        vuln = importer.db.query(Vulnerability).filter(
            Vulnerability.asset_id == asset.id,
            Vulnerability.template_id == template_id,
            Vulnerability.status.in_(_RESOLVABLE_STATUSES),
        ).first()
        if vuln is None:
            continue
        vuln.status = VulnerabilityStatus.RESOLVED
        vuln.resolved_at = _parse_datetime(finding.get("last_fixed")) or datetime.utcnow()
        metadata = dict(vuln.metadata_ or {})
        metadata["tenable_state"] = "FIXED"
        vuln.metadata_ = metadata
        importer.stats.vulns_resolved += 1


def _retire_stale_assets(importer: "TenableImporter") -> None:
    """Mark Tenable-created assets Tenable no longer reports as INACTIVE.

    Only assets Tenable itself created are retired; assets found by other
    discovery and merely enriched by Tenable are left alone.
    """
    stale = importer.db.query(Asset).filter(
        Asset.organization_id == importer.org_id,
        Asset.discovery_source == DISCOVERY_SOURCE,
        Asset.status.notin_([AssetStatus.INACTIVE, AssetStatus.ARCHIVED]),
    ).all()
    now = datetime.utcnow().isoformat()
    for asset in stale:
        if asset.id in importer._touched_assets:
            continue
        asset.status = AssetStatus.INACTIVE
        metadata = dict(asset.metadata_ or {})
        metadata["tenable"] = {**(metadata.get("tenable") or {}), "retired_at": now}
        asset.metadata_ = metadata
        importer.stats.assets_retired += 1


def acquire_sync_lock(db: Session, integration_id: int) -> bool:
    """Atomically claim the connection's sync lock. False if a sync is running."""
    now = datetime.utcnow()
    claimed = (
        db.query(TenableVmIntegration)
        .filter(
            TenableVmIntegration.id == integration_id,
            (TenableVmIntegration.sync_started_at.is_(None))
            | (TenableVmIntegration.sync_started_at < now - SYNC_LOCK_TTL),
        )
        .update({TenableVmIntegration.sync_started_at: now}, synchronize_session=False)
    )
    db.commit()
    return claimed == 1


def _client_for(integration: TenableVmIntegration) -> TenableClient:
    access_key = integration.get_access_key()
    secret_key = integration.get_secret_key()
    if not access_key or not secret_key:
        raise TenableApiError("No Tenable VM API keys are stored for this connection.")
    return TenableClient(integration.base_url, access_key, secret_key)


async def sync_integration(
    db: Session,
    integration: TenableVmIntegration,
    *,
    client: Optional[TenableClient] = None,
    address_filter: Optional[_AddressFilter] = None,
    lock_held: bool = False,
) -> Dict[str, Any]:
    """Run one sync. Takes the connection's lock unless the caller already holds it."""
    if not lock_held and not acquire_sync_lock(db, integration.id):
        return {"ok": False, "message": "A sync is already running for this connection."}
    db.refresh(integration)
    importer = TenableImporter(db, integration.organization_id, address_filter)
    try:
        backfill_identifiers(db, integration.organization_id, DISCOVERY_SOURCE, "source:tenable")
        client = client or _client_for(integration)
        since = _since_epoch()
        asset_records: Optional[List[Dict[str, Any]]] = None
        if integration.import_assets:
            asset_records = await client.export_assets(since)
            importer.import_assets(asset_records)
        if integration.import_vulnerabilities:
            importer.import_vulnerabilities(await client.export_vulns(since))
            _resolve_fixed(importer, await client.export_fixed_vulns(since))
        # Only retire after a complete, non-empty asset export: an empty
        # export is far more likely a permissions problem than an empty estate.
        if asset_records:
            _retire_stale_assets(importer)

        stats = importer.stats.as_dict()
        integration.last_sync_at = datetime.utcnow()
        integration.last_sync_ok = True
        integration.last_error = None
        integration.last_sync_stats = stats
        integration.sync_started_at = None
        db.commit()
        return {
            "ok": True,
            "message": (
                f"Imported {stats['assets_created']} new asset(s) and "
                f"{stats['vulns_created']} new vulnerability finding(s) from Tenable VM; "
                f"closed {stats['vulns_resolved']} fixed finding(s), retired "
                f"{stats['assets_retired']} asset(s) no longer reported, and skipped "
                f"{stats['assets_skipped']} private/internal/cloud asset(s)."
            ),
            **stats,
        }
    except Exception as exc:  # noqa: BLE001
        db.rollback()
        logger.exception("Tenable VM sync failed for organization %s", integration.organization_id)
        integration.last_sync_at = datetime.utcnow()
        integration.last_sync_ok = False
        integration.last_error = str(exc)[:1000]
        integration.sync_started_at = None
        db.commit()
        return {"ok": False, "message": f"Sync failed: {exc}", **importer.stats.as_dict()}
